#!/usr/bin/env python3
"""Generate the simple 'auto' series from existing records (successions, lineages of lifespans, book list).

Output: data/series/auto-<id>.json  (auto: true — regenerated on every run, do not hand-edit)
Curated series (prophecy/fulfillment, world powers, covenants, chart reproductions) are hand-researched files
in data/series/ without the auto- prefix.
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load():
    evs = {}
    files = [p for p in glob.glob(os.path.join(ROOT, "data/raw/b*.json")) if re.fullmatch(r"b\d+\.json", os.path.basename(p))]
    files += glob.glob(os.path.join(ROOT, "data/derived/d*.json"))
    for f in files:
        for e in json.load(open(f, encoding="utf-8"))["events"]:
            evs[e["id"]] = e
    return evs


def top_sources(members, evs, n=3):
    count, first = {}, {}
    for m in members:
        for s in evs[m]["sources"]:
            count[s["docid"]] = count.get(s["docid"], 0) + 1
            first.setdefault(s["docid"], {k: s.get(k) for k in ("docid", "publication", "title_en", "title_ta", "url_en", "url_ta", "finder_url")})
    return [first[d] for d, _ in sorted(count.items(), key=lambda kv: -kv[1])[:n]]


def series(sid, title, kind, desc, member_ids, evs, role="ruler", parent=None, highlight=False, labels=None):
    member_ids = [m for m in member_ids if m in evs]
    return {
        "id": sid, "title_en": title, "title_ta": None, "kind": kind, "description_en": desc, "description_ta": None,
        "highlight": highlight, "auto": True, "parent_series": parent,
        "sources": top_sources(member_ids, evs), "images": [], "groups": [],
        "members": [{"event_id": m, "order": i, "role": role, "group": None,
                     "label_en": (labels or {}).get(m) or evs[m]["title_en"], "label_ta": evs[m].get("title_ta"),
                     "pairs_with": [], "scriptures": [], "source_docid": None, "note": None}
                    for i, m in enumerate(member_ids, 1)],
        "notes": "Generated by scripts/build_series.py from existing records; sources are those of the member records.",
    }


def by_start(ids, evs):
    return sorted(ids, key=lambda i: (evs[i]["start"]["sort_key"], i))


def main():
    evs = load()
    out = []
    spans = [e for e in evs.values() if e["timing"] == "span"]

    def find(pred):
        return by_start([e["id"] for e in spans if pred(e)], evs)

    out.append(series("kings-of-judah", "Kings of Judah", "succession",
                      "The kings of the southern two-tribe kingdom of Judah, 997–607 B.C.E., in the order of NWT Appendix A6.",
                      find(lambda e: e["span_kind"] == "reign" and "kingdom-of-judah" in e.get("tags", [])), evs, parent="prophets-and-kings-a6"))
    out.append(series("kings-of-israel", "Kings of Israel", "succession",
                      "The kings of the northern ten-tribe kingdom of Israel, 997–740 B.C.E., in the order of NWT Appendix A6.",
                      find(lambda e: e["span_kind"] == "reign" and "kingdom-of-israel" in e.get("tags", [])), evs, parent="prophets-and-kings-a6"))
    out.append(series("united-kingdom", "Kings of the united kingdom of Israel", "succession",
                      "Saul, David and Solomon ruled all twelve tribes, 1117–997 B.C.E.",
                      ["b12-0009", "b12-0012", "b12-0013"], evs))
    out.append(series("rulers-of-persia", "Rulers of Persia in the Bible record", "succession",
                      "Persian kings who appear in the Bible record, from Cyrus the Great to Artaxerxes I.",
                      find(lambda e: e["span_kind"] == "reign" and e["id"].startswith("b12") and re.search(r"Cyrus|Darius|Xerxes|Artaxerxes", e["title_en"])), evs))
    out.append(series("roman-emperors", "Roman emperors of the first century", "succession",
                      "Roman emperors from Augustus to Trajan, covering the life of Jesus and the apostolic period.",
                      find(lambda e: e["span_kind"] == "reign" and ("Roman emperor" in e["title_en"])), evs))
    out.append(series("watch-tower-presidents", "Presidents of the Watch Tower Society", "succession",
                      "The presidents of the Watch Tower Bible and Tract Society from C. T. Russell onward.",
                      find(lambda e: e["span_kind"] == "office" and "president of the Watch Tower" in e["title_en"]), evs))
    out.append(series("governing-body", "Members of the Governing Body", "succession",
                      "Tenures of Governing Body members that jw.org dates.",
                      find(lambda e: e["span_kind"] == "office" and "Governing Body" in e["title_en"]), evs))
    judges = find(lambda e: e["span_kind"] == "judgeship") + [i for i in ("b2-0071",) if i in evs]
    out.append(series("judges-of-israel", "Judges of Israel", "succession",
                      "Judges who delivered Israel between the conquest and the kings. Most of their years are not stated on jw.org; the order follows the book of Judges.",
                      sorted(judges, key=lambda i: evs[i]["start"]["sort_key"]), evs, parent=None))
    books = sorted([e["id"] for e in evs.values() if e["category"] == "bible.book_writing" and e["id"].startswith("b11")
                    and e.get("event_kind") == "writing_completed"],
                   key=lambda i: (evs[i]["scriptures"][0].get("book_num") or 99) if evs[i].get("scriptures") else 99)
    out.append(series("bible-books-written", "The 66 Bible books: when writing was completed", "theme",
                      "When each of the 66 books of the Bible was completed, in canonical order (NWT Table of the Books of the Bible).",
                      books, evs, role="item"))
    pre = ["d1-0001", "d1-0002", "d1-0003", "d1-0004", "d1-0005", "d1-0006"]
    post = ["d1-0007", "d1-0008", "d1-0009", "d1-0010", "d1-0011", "d1-0012", "d1-0013", "d1-0014", "d1-0015", "d1-0016"]
    out.append(series("pre-flood-patriarchs", "Lives of the patriarchs before the Flood", "lineage",
                      "The overlapping long lives from Adam to Noah, from Genesis 5 as dated in 'All Scripture Is Inspired' Study 3.",
                      pre, evs, role="item"))
    out.append(series("post-flood-patriarchs", "Lives of the patriarchs after the Flood", "lineage",
                      "From Shem to Joseph: lifespans dated from Genesis 11 and the patriarch accounts.",
                      post, evs, role="item"))

    for f in glob.glob(os.path.join(ROOT, "data/series/auto-*.json")):
        os.remove(f)
    for s in out:
        json.dump(s, open(os.path.join(ROOT, f"data/series/auto-{s['id']}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"auto-{s['id']}: {len(s['members'])} members")


if __name__ == "__main__":
    main()
